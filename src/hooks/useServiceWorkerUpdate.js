// Service-worker update signal for the "A new version is ready" toast
// (DESKTOP_AND_PWA_PLAN.md, Part 1).
//
// vite-plugin-pwa runs in `registerType: 'autoUpdate'` mode: a fresh deploy
// installs and activates on the next page load without asking. Its
// register helper then either hard-reloads the page or, when `onNeedReload`
// is supplied, hands the decision to us — which matters on a kitchen
// display mid-service where an unannounced reload would wipe the screen.
// We flip `needRefresh` and let the user press Reload.
//
// The register module is virtual (`virtual:pwa-register`, generated by the
// plugin) so it is loaded lazily inside an effect: in jsdom there is no
// `navigator.serviceWorker`, so nothing is imported and tests never touch
// it; if the import ever fails (e.g. a build without the plugin, or the
// Electron shell pointing at an old server) the hook just stays idle.
import { useCallback, useEffect, useRef, useState } from 'react'

function canUseServiceWorker() {
  if (typeof window === 'undefined' || typeof navigator === 'undefined') return false
  // Inside the BestoDine desktop app the shell owns offline handling (its
  // own "Can't reach BestoDine" page with auto-retry). A service worker
  // would serve the cached index.html instead, so the shell never notices
  // the outage and users see a half-working page with failing API calls.
  if (window.bestodine && window.bestodine.isDesktop === true) return false
  return 'serviceWorker' in navigator
}

function defaultReload() {
  try {
    window.location.reload()
  } catch {
    // jsdom: location.reload is not implemented.
  }
}

/**
 * @param {{ reload?: () => void }} [options] test seam for the page reload
 * @returns {{ needRefresh: boolean, update: () => Promise<void> }}
 */
export default function useServiceWorkerUpdate({ reload = defaultReload } = {}) {
  const [needRefresh, setNeedRefresh] = useState(false)
  // `updateServiceWorker` returned by registerSW — only meaningful in
  // 'prompt' mode (it messages skipWaiting); harmless in autoUpdate.
  const updateSWRef = useRef(null)

  useEffect(() => {
    if (!canUseServiceWorker()) return undefined
    let cancelled = false
    import('virtual:pwa-register')
      .then(({ registerSW }) => {
        if (cancelled || typeof registerSW !== 'function') return
        updateSWRef.current = registerSW({
          immediate: true,
          // autoUpdate: new SW already activated — ask before reloading.
          onNeedReload: () => { if (!cancelled) setNeedRefresh(true) },
          // prompt mode (not used today, kept so a config switch still works).
          onNeedRefresh: () => { if (!cancelled) setNeedRefresh(true) },
          onRegisterError: () => {},
        })
      })
      .catch(() => {
        // No service worker in this build/environment — stay idle.
      })
    return () => { cancelled = true }
  }, [])

  const update = useCallback(async () => {
    try {
      await updateSWRef.current?.(false)
    } catch {
      // Fall through to the reload; the new worker is already active.
    }
    reload()
  }, [reload])

  return { needRefresh, update }
}
